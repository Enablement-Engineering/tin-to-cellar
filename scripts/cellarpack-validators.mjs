import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
import ucs2length from 'ajv/dist/runtime/ucs2length.js'

// Preserve the importer's validation semantics while removing browser compilation.
const source = await readFile(new URL('../src/lib/cellarpack/cellarpack-v1.schema.json', import.meta.url), 'utf8')
const schema = JSON.parse(source)
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true, lines: true } })
const schemas = {
  validateManifestSchema: schema,
  validateAssetMapSchema: { ...schema.properties.assets, $defs: schema.$defs, additionalProperties: true },
  validateLabelSchema: { $schema: schema.$schema, $defs: schema.$defs, ...schema.$defs.label },
  validateAssetSchema: { $schema: schema.$schema, $defs: schema.$defs, ...schema.$defs.artworkAsset },
}
for (const [name, definition] of Object.entries(schemas)) ajv.addSchema(definition, name)
let code = standaloneCode(ajv, Object.fromEntries(Object.keys(schemas).map(name => [name, name])))
// AJV emits this helper as CommonJS even with ESM output; embed its implementation.
code = code.replaceAll('require("ajv/dist/runtime/ucs2length").default', `(${ucs2length.default.toString()})`)
if (/\brequire\s*\(/.test(code)) throw new Error('Standalone CellarPack validator has an unsupported runtime dependency')
await writeFile(new URL('../src/lib/cellarpack/validators.generated.js', import.meta.url), `// Generated by npm run cellarpack:validators. Do not edit.\n// Schema SHA-256: ${createHash('sha256').update(source).digest('hex')}\n${code}`)
