import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import Ajv from 'ajv'
import standaloneCode from 'ajv/dist/standalone/index.js'
import ucs2length from 'ajv/dist/runtime/ucs2length.js'

// Compile once for both browser and Worker: no eval/Function in either runtime.
// Strict schema compilation fails the build on unsupported validation keywords.
const ajv = new Ajv({ strict: true, allErrors: false, code: { source: true, esm: true, lines: true } })
const schemas = { validateCurrent: 'schema', validateLegacy: 'legacy-schema', validateHistorical: 'historical-schema' }
const digest = createHash('sha256')
for (const [name, file] of Object.entries(schemas)) {
  const source = await readFile(new URL(`../src/lib/feedback/${file}.json`, import.meta.url), 'utf8')
  digest.update(source)
  ajv.addSchema(JSON.parse(source), name)
}
let code = standaloneCode(ajv, Object.fromEntries(Object.keys(schemas).map(name => [name, name])))
// AJV emits a CommonJS reference for this helper even in ESM mode. Embed its
// canonical implementation so the output needs no module loader or AJV engine.
code = code.replaceAll('require("ajv/dist/runtime/ucs2length").default', `(${ucs2length.default.toString()})`)
if (/\brequire\s*\(/.test(code)) throw new Error('Standalone feedback validator has an unsupported runtime dependency')
await writeFile(new URL('../src/lib/feedback/validators.generated.js', import.meta.url), `// Generated by npm run feedback:validators. Do not edit.\n// Schema SHA-256: ${digest.digest('hex')}\n${code}`)
